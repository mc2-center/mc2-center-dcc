"""
upload_recordsets.py

Uploads split manifests to the shared RecordSets listed in the gen-mp-csv.py
output. For each grant it finds ``MC2Center_<Component>_RecordSet`` in the
grant's data-type folder (a missing RecordSet stops that grant; creating it is
a migration step), folds in contributor edits made since the pipeline's last
write (``portal_tables/recordsets.py``: reconcile, then merge the upload), and
writes the result through a Grid session so Synapse validates it.

Dry run is the default: everything is computed and reported, nothing is
written to Synapse and validation is skipped. Use ``--execute`` to write; it
needs ``--write-log-table`` (a CSV log is for dry runs and tests). The state is
rebuilt by a deterministic replay of every version with per-cell ownership
(see ``portal_tables/recordsets.py``); a cell owned by a contributor is never
overwritten by the upload and is reported in conflicts.csv. A grant whose
RecordSet has another run's unfinished write (a pending write-log row under
2 h old) is skipped with status ``locked``.
Reports go to ``<report-dir>/<run-id>/<grant>/``: decisions.csv, conflicts.csv,
validation.csv (``--execute`` only), merged.csv and summary.txt.

Upload rows whose key a DCC row removal (D-Q49) removed are dropped after the
replay and before the merge, and listed in removal_skipped.csv. The removed keys
come from the write log's ``removed`` versions and the history (so a removal
the removals table doesn't list yet counts) and from the removals table's
``removed`` rows; a key whose latest status is ``restored`` is uploaded
normally. ``--execute`` needs a removals source (``--removals-table``, or
``--removals-csv`` in tests); a dry run may omit it, and then ``restored`` keys
are unknown.

The exit status is 1 if any grant needs attention (failed, missing_recordset,
locked, retry or verification_mismatch), so a workflow does not treat the
upload as done; the other grants still run. If foreign versions landed during a
write, the grant is replayed and written once more immediately (the report goes
to a ``rerun`` subfolder).

author: orion.banks
"""

import argparse
import logging
import os
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd

# removed when the mc2dcc package (CLI consolidation plan) lands
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "portal_tables"))
import model_contract
import recordsets
import utils

logger = logging.getLogger(__name__)

# Statuses that make the exit code non-zero, so a workflow does not mark the upload done.
NEEDS_ATTENTION = frozenset(
    {"failed", "missing_recordset", "locked", "retry", "verification_mismatch"}
)

PROCESS_START = pd.Timestamp.now(tz="UTC")  # a pending row of our runId older than this is not ours


def get_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.strip().split("\n")[0])
    parser.add_argument("--paths-csv", required=True, help="CSV generated by gen-mp-csv.py")
    parser.add_argument(
        "--component",
        required=True,
        choices=["PublicationView", "DatasetView", "ToolView", "EducationalResource", "GrantView"],
        help="component of the manifests, e.g. PublicationView",
    )
    log = parser.add_mutually_exclusive_group(required=True)
    log.add_argument("--write-log-table", help="Synapse ID of the write-log table (required with --execute)")
    log.add_argument("--write-log-csv", help="local CSV write log (dry runs and tests only)")
    removals = parser.add_mutually_exclusive_group()
    removals.add_argument("--removals-table", help="Synapse ID of the removals table (D-Q49)")
    removals.add_argument("--removals-csv", help="local CSV removals table (dry runs and tests only)")
    parser.add_argument("--report-dir", required=True, help="directory for the per-grant reports")
    parser.add_argument(
        "--execute", action="store_true", help="write to Synapse; the default is a dry run"
    )
    parser.add_argument(
        "--cache-dir",
        default=str(recordsets.DEFAULT_CACHE_DIR),
        help="on-disk cache of downloaded RecordSet versions (immutable); default: %(default)s",
    )
    parser.add_argument(
        "--run-id", default=datetime.now().strftime("%Y%m%dT%H%M%S"), help="default: a timestamp"
    )
    args = parser.parse_args(argv)
    if args.execute and not args.write_log_table:
        parser.error("--execute needs --write-log-table; a CSV log is for dry runs and tests only")
    if args.execute and not (args.removals_table or args.removals_csv):
        parser.error("--execute needs --removals-table (or --removals-csv) so removed rows are not uploaded again")
    return args


def folder_column(paths: pd.DataFrame) -> str:
    """The gen-mp-csv.py folder ID column (``folderIdPublication``, ...)."""
    matches = [c for c in paths.columns if c.startswith("folderId")]
    if len(matches) != 1:
        raise ValueError(f"Expected one folderId* column in the paths CSV, found {matches}")
    return matches[0]


def stored_keys(df: pd.DataFrame, key_cols: list[str]) -> list[str]:
    return [recordsets._key_of(row, key_cols) for _, row in df.iterrows()]


def process_grant(syn, row, args, write_log, report_dir: Path, list_cols, set_like, _rerun=False,
                  removals=None) -> dict:
    """Upload one grant's manifest. Returns a summary dict with a ``status``."""
    component = args.component
    summary = {"grant": report_dir.name, "file": row["File Paths"], "status": "", "message": ""}

    upload = pd.read_csv(row["File Paths"], dtype=str, keep_default_na=False)
    upload = model_contract.normalize_headers(upload, to="keys")
    # Synapse keeps only schema properties on a Grid import (Component is not one).
    extra = [c for c in upload.columns if c not in recordsets.schema_columns(component)]
    if extra:
        logger.info("%s: not stored in the RecordSet, dropped: %s", report_dir.name, extra)
        upload = upload.drop(columns=extra)
    upload = recordsets.parse_upload(upload, list_cols)
    summary["new_comma_terms"] = len(recordsets.learn_comma_terms(upload, component))

    folder_id = row[folder_column_name(row)]
    if folder_id in ("", "None", "nan"):
        summary.update(status="failed", message="no data-type folder ID in the paths CSV")
        return summary
    rs_id = recordsets.find_recordset(syn, folder_id, component)
    if rs_id is None:
        summary.update(status="missing_recordset", message=(
            f"MC2Center_{component}_RecordSet not found in {folder_id}; "
            "create it as a migration step"))
        return summary
    summary["recordset"] = rs_id

    latest, key = recordsets.recordset_info(syn, rs_id)
    if not key:
        summary.update(status="failed", message=f"{rs_id} has no upsert key")
        return summary
    absent = [c for c in key if c not in upload.columns]
    if absent:
        summary.update(status="failed", message=f"upload lacks key column(s) {absent}")
        return summary
    try:
        upload = recordsets.check_upload_keys(upload, key)
    except ValueError as err:
        summary.update(status="failed", message=f"bad upload keys: {err}")
        return summary

    locker = write_log.locked_by(rs_id, args.run_id, since=PROCESS_START)
    if locker:
        summary.update(status="locked", message=(
            f"run {locker} has an unfinished write (pending row under {recordsets.LOCK_HOURS} h old); skipped"))
        return summary

    # A run that died after exporting leaves a pending row; claim its versions.
    recovered = recordsets.recover_pending(
        syn, rs_id, write_log, latest, record=args.execute, skip_younger_than=recordsets.LOCK_HOURS
    )
    if recovered:
        summary["recovered"] = sorted(recovered)
    log_map = {**write_log.pipeline_map(rs_id), **recovered}
    if log_map and latest < max(log_map):
        summary.update(status="failed", message=f"write log has v{max(log_map)} but {rs_id} is at v{latest}")
        return summary

    def read(v):
        df = recordsets.read_recordset(
            syn, rs_id, version=v, cache_dir=args.cache_dir, list_cols=list_cols
        )
        dupes = recordsets.duplicate_keys(df, key)
        if dupes:
            logger.warning("%s v%s has duplicate keys (the last row of each wins): %s", rs_id, v, dupes)
        return df

    versions = [(v, read(v)) for v in range(1, latest + 1)]
    current = versions[-1][1]
    removal_versions = write_log.removal_versions(rs_id) | set(recovered.removal)
    restored = removals.restored(rs_id) if removals is not None else set()
    base, owned, decisions = recordsets.replay(versions, log_map, key, set_like, removal_versions, restored)
    # D-Q49: a removed row is not uploaded again until its key is ``restored``. The removed keys
    # come from the history (so a removal the table doesn't list yet counts) and the table.
    removed = recordsets.removed_keys(versions, {v: log_map[v] for v in removal_versions if v in log_map}, key)
    if removals is not None:
        removed.update(removals.removed(rs_id))
    removed = {k: v for k, v in removed.items() if k not in restored}
    upload, skipped = recordsets.drop_removed(upload, key, removed)
    report_dir.mkdir(parents=True, exist_ok=True)
    _write_report(report_dir / "removal_skipped.csv", skipped)
    if len(skipped):
        summary["removal_skipped"] = len(skipped)
        logger.info("%s: %d upload row(s) skipped, key removed by the DCC (removal_skipped.csv)",
                    report_dir.name, len(skipped))
    mode = "first write (no replay)" if not log_map else f"replayed v1..v{latest}"
    merged, conflicts = recordsets.merge_upload(base, upload, key, owned, set_like)
    # Columns that are no longer schema properties are dropped by a Grid import; compare without them.
    stored = recordsets.schema_columns(component) | set(key)
    merged = merged[[c for c in merged.columns if c in stored]]
    report_dir.mkdir(parents=True, exist_ok=True)
    merged_path = report_dir / "merged.csv"
    recordsets.to_csv(merged, merged_path)
    _write_report(report_dir / "decisions.csv", decisions)
    _write_report(report_dir / "conflicts.csv", conflicts)

    summary.update(rows=len(merged), decisions=len(decisions), conflicts=len(conflicts), mode=mode)
    # Nothing to write: every version adds to the history later runs read.
    if not recordsets.differences(merged, _only(current, stored), key, set_like):
        summary.update(status="unchanged", message=f"{mode}; RecordSet already matches; nothing written")
        return summary
    if not args.execute:
        summary.update(status="dryrun", message=f"dry run: {mode}; nothing written")
        return summary

    principal = principal_id(syn)
    try:
        created = recordsets.write_logged(
            syn, rs_id, merged_path, write_log, args.run_id, principal, len(merged), latest
        )
    except recordsets.WriteRefused as refused:
        summary.update(status=refused.status, message=refused.message)
        return summary
    version = created[-1]
    summary["version"] = version

    written = read(version)
    problems = recordsets.differences(merged, _only(written, stored), key, set_like)
    validation = recordsets.get_validation(syn, rs_id, version, report_dir, stored_keys(written, key))
    if validation is not None:
        validation.to_csv(report_dir / "validation.csv", index=False)
        summary["invalid_rows"] = int((~validation["is_valid"].astype(str).str.lower().eq("true")).sum())
    notes = [f"wrote v{version}"]
    midwrite = [v for v in range(latest + 1, version) if v not in created]
    if midwrite:
        summary["foreign_midwrite"] = midwrite
        notes.append(f"foreign versions landed mid-write: {midwrite}; the next run's replay handles them")
    newest, _ = recordsets.recordset_info(syn, rs_id)
    status = "written"
    if summary.get("invalid_rows"):
        status = "written_with_invalid"
    if newest > version:
        status = "changed_after_write"
        notes.append(f"v{newest} exists after the write; the next run's replay handles it")
    if problems:
        (report_dir / "verification.txt").write_text("\n".join(problems) + "\n")
        status = "verification_mismatch"
        notes.append(f"v{version} differs from the merged frame ({len(problems)} differences)")
    summary.update(status=status, message=f"{mode}; " + "; ".join(notes))
    if midwrite and not _rerun and status not in ("verification_mismatch",):
        # Replay once more now: it restores the edits our write overwrote.
        first = dict(summary)
        second = process_grant(syn, row, args, write_log, report_dir / "rerun", list_cols, set_like, _rerun=True,
                              removals=removals)
        second["grant"] = first["grant"]
        second["rerun"] = True
        second["message"] = (
            f"rerun after foreign versions {midwrite} landed mid-write "
            f"(first pass {first['status']}, v{first['version']}); {second['message']}"
        )
        return second
    return summary


def _only(df: pd.DataFrame, columns) -> pd.DataFrame:
    return df[[c for c in df.columns if c in columns]]


def principal_id(syn) -> str:
    return recordsets.principal_id(syn)


def folder_column_name(row) -> str:
    return next(c for c in row.index if c.startswith("folderId"))


def _write_report(path: Path, df: pd.DataFrame) -> None:
    recordsets.to_csv(df, path)


def summary_line(s: dict) -> str:
    parts = [f"{s['grant']}: {s['status']}"]
    for field in ("recordset", "version", "rows", "decisions", "conflicts", "invalid_rows", "recovered", "foreign_midwrite", "removal_skipped"):
        if field in s:
            parts.append(f"{field}={s[field]}")
    if s["message"]:
        parts.append(s["message"])
    return " ".join(parts)


def main(argv=None, syn=None):
    args = get_args(argv)
    syn = syn or utils.syn_login()
    write_log = (
        recordsets.SynapseTableWriteLog(syn, args.write_log_table)
        if args.write_log_table
        else recordsets.CsvWriteLog(args.write_log_csv)
    )
    removals = (
        recordsets.SynapseTableRemovals(syn, args.removals_table) if args.removals_table
        else recordsets.CsvRemovals(args.removals_csv) if args.removals_csv else None
    )
    list_cols = recordsets.list_columns(args.component)
    set_like = recordsets.set_like_columns(args.component)
    paths = pd.read_csv(args.paths_csv, dtype=str, keep_default_na=False)
    folder_column(paths)  # fail early on a malformed paths CSV
    run_dir = Path(args.report_dir) / args.run_id
    print(f"Run {args.run_id}: {'EXECUTE' if args.execute else 'dry run'}, {len(paths)} grants")

    summaries, failed = [], 0
    for _, row in paths.iterrows():
        grant = row.get("grantId") or Path(row["File Paths"]).stem
        report_dir = run_dir / str(grant)
        try:
            summary = process_grant(syn, row, args, write_log, report_dir, list_cols, set_like, removals=removals)
        except Exception as err:  # one grant's failure must not stop the others
            logger.exception("Grant %s failed", grant)
            summary = {"grant": str(grant), "file": row["File Paths"], "status": "failed", "message": repr(err)}
        if summary["status"] in NEEDS_ATTENTION:
            failed += 1
        report_dir.mkdir(parents=True, exist_ok=True)
        line = summary_line(summary)
        (report_dir / "summary.txt").write_text(line + "\n")
        print(line)
        summaries.append(summary)

    pd.DataFrame(summaries).to_csv(run_dir / "summary.csv", index=False)
    new_terms = sum(s.get("new_comma_terms", 0) for s in summaries)
    if new_terms:
        print(f"{new_terms} new comma-containing term(s) added to portal_tables/comma_terms.csv; commit the file")
    print(f"{len(summaries) - failed} of {len(summaries)} grants ok; {failed} need attention")
    return 1 if failed else 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    sys.exit(main())
